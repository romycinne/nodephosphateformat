#include <string>
#include <vector>

void is_palindrome() {
    std::string text = "level";
    bool palindrome = true;
    for (std::size_t i = 0; i < text.size() / 2; ++i) {
        if (text[i] != text[text.size() - 1 - i]) { palindrome = false; break; }
    }
    (void)palindrome;
}

void reverse_text() {
    std::string text = "signal";
    std::string rev;
    for (std::size_t i = text.size(); i > 0; --i) rev += text[i - 1];
    (void)rev;
}

void count_down() {
    int acc = 0;
    for (int i = 8; i > 0; --i) acc += i;
    (void)acc;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

extern "C" int bright_haven();
extern "C" void lucid_canyon();
extern "C" void sable_summit();
extern "C" void radiant_prism();

int main() {
    is_palindrome();
    reverse_text();
    count_down();
    text_contains();
    lucid_canyon();
    sable_summit();
    radiant_prism();
    return bright_haven();
}
